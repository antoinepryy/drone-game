static const Glyph *find_glyph(char c)
{
    c = (char)toupper((unsigned char)c);
    for (size_t i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); i++) {
        if (GLYPHS[i].c == c) {
            return &GLYPHS[i];
        }
    }
    return NULL;   /* space and unknown characters are left blank */
}

float font_width(const char *text, float scale)
{
    size_t n = strlen(text);
    return n == 0 ? 0.0f : (float)n * 6.0f * scale - scale;
}

void font_draw(SDL_Renderer *r, float x, float y, float scale, const char *text)
{
    for (const char *p = text; *p; p++, x += 6.0f * scale) {
        const Glyph *g = find_glyph(*p);
        if (!g) {
            continue;
        }
        for (int row = 0; row < 7; row++) {
            for (int col = 0; col < 5; col++) {
                if (g->rows[row] & (0x10 >> col)) {
                    SDL_FRect px = {x + col * scale, y + row * scale, scale, scale};
                    SDL_RenderFillRectF(r, &px);
                }
            }
        }
    }
}
